def get_language(raw: str | None) -> str:
    if raw in SUPPORTED_LANGS:
        return raw
    return DEFAULT_LANG


def translate(key: str, lang: str | None = None, **kwargs: Any) -> str:
    active_lang = get_language(lang)
    template = TRANSLATIONS.get(active_lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key
    return template.format(**kwargs) if kwargs else template
